const {launch}=require('./_launch.cjs');
const {setup}=require('./_ha-mock.cjs');
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..'),boot=JSON.parse(fs.readFileSync(root+'/ha/bootstrap.json'));
boot.catalog=Array.from({length:18},(_,i)=>({id:'test.app'+i,title:'Test app '+i,visible:true}));
(async()=>{const browser=await launch();try{for(const width of [1920,1280]){
 const page=await browser.newPage({viewport:{width,height:width*1080/1920}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(setup,{boot});await page.goto('file://'+root+'/src/com.spinoff.lumahome/index.html');
 await page.locator('#launcherTiles .launcher-tile').last().waitFor();
 const drawer=page.locator('#launcherDrawer'),launcher=page.locator('#launcher');
 const panel=await launcher.boundingBox();
 await page.mouse.move(panel.x+panel.width/2,panel.y+panel.height/2);
 await page.mouse.wheel(0,550);
 await page.waitForFunction(()=>document.getElementById('launcher').scrollTop>300);
 const dock=page.locator('#launcherDock .launcher-tile');
 await dock.first().focus();
 for(let i=0;i<5;i++)await page.keyboard.press('ArrowDown');
 await page.keyboard.press('ArrowRight');
 const focused=await page.evaluate(()=>{const items=Array.from(document.querySelectorAll('#launcherTiles .launcher-tile'));return [items.indexOf(document.activeElement),items.length];});
 assert.ok(focused[0]>=focused[1]-4,'remote reached the final app row');
 const active=await page.locator('.launcher-tile:focus').boundingBox();
 assert(active.y+active.height<=panel.y+panel.height+2,'focused tile is fully visible');
 assert(await drawer.locator('.launcher-tile').count()>10);
 for(let i=0;i<5;i++)await page.keyboard.press('ArrowUp');
 assert.equal(await launcher.evaluate(el=>el.scrollTop),0);
 assert.deepStrictEqual(errors,[]);await page.close();
 }console.log('Passed: scrolling and D-pad navigation in the vertical app drawer at 1080p and 720p.');}finally{await browser.close();}})().catch(e=>{console.error(e);process.exitCode=1;});
